package j5i.spatial8d.ui

import android.content.Context
import android.content.res.Configuration
import android.content.res.Resources
import java.util.Locale

/** 应用内语言；第三方歌曲、歌手、电台与 API 内容不经过翻译。 */
object AppLanguage {
    private const val PREF = "language"
    const val SYSTEM = "system"
    const val SIMPLIFIED = "zh-CN"
    const val TRADITIONAL = "zh-TW"
    const val ENGLISH = "en"

    fun current(context: Context): String =
        context.getSharedPreferences("spatial8d", Context.MODE_PRIVATE).getString(PREF, SYSTEM) ?: SYSTEM

    fun systemLanguage(locale: Locale): String = when (locale.language) {
        "zh" -> if (locale.script == "Hant" || locale.country in setOf("TW", "HK", "MO")) TRADITIONAL else SIMPLIFIED
        "en" -> ENGLISH
        else -> SIMPLIFIED
    }

    fun resolved(context: Context): String = when (val selected = current(context)) {
        SYSTEM -> systemLanguage(Resources.getSystem().configuration.locales[0] ?: Locale.SIMPLIFIED_CHINESE)
        SIMPLIFIED, TRADITIONAL, ENGLISH -> selected
        else -> SIMPLIFIED
    }

    fun select(context: Context, value: String) {
        context.getSharedPreferences("spatial8d", Context.MODE_PRIVATE).edit().putString(PREF, value).apply()
    }

    fun wrap(context: Context): Context {
        val locale = when (resolved(context)) {
            SIMPLIFIED -> Locale.SIMPLIFIED_CHINESE
            TRADITIONAL -> Locale.TRADITIONAL_CHINESE
            else -> Locale.ENGLISH
        }
        return context.createConfigurationContext(Configuration(context.resources.configuration).apply { setLocale(locale) })
    }

    fun text(context: Context, key: String): String = textForLanguage(resolved(context), key)

    fun error(context: Context, message: String?): String = errorForLanguage(resolved(context), message)

    fun mvQuality(context: Context, label: String): String = mvQualityForLanguage(resolved(context), label)

    fun artist(context: Context, value: String): String =
        if (value == "未知歌手") text(context, "metadata.unknown_artist") else value

    fun album(context: Context, value: String): String =
        if (value == "未知专辑") text(context, "metadata.unknown_album") else value

    internal fun mvQualityForLanguage(language: String, label: String): String {
        val key = when (label) {
            "流畅" -> "mv.quality.smooth"
            "标清" -> "mv.quality.standard"
            "高清" -> "mv.quality.high"
            "超清" -> "mv.quality.ultra"
            "蓝光" -> "mv.quality.bluray"
            else -> null
        }
        if (key != null) return textForLanguage(language, key)
        val quality = Regex("清晰度 ([0-9]+)").matchEntire(label)?.groupValues?.get(1) ?: return label
        return textForLanguage(language, "mv.quality.number").format(quality)
    }

    internal fun isFirstPartyErrorOrigin(origin: String): Boolean =
        origin.startsWith("j5i.spatial8d.provider.") || origin.startsWith("j5i.spatial8d.core.") ||
            origin.startsWith("j5i.spatial8d.audio.") || origin.startsWith("j5i.spatial8d.data.") ||
            origin.startsWith("j5i.spatial8d.ui.VideoExport")

    internal fun errorForLanguage(language: String, message: String?): String {
        if (message == null) return ""
        val direct = errorEntries[message]
        if (direct != null) return when (language) {
            TRADITIONAL -> direct.traditional
            ENGLISH -> direct.english
            else -> direct.simplified
        }
        val patterns = listOf(
            "字段路径无效: " to "error.field_path",
            "电台信息过长: " to "error.station_field",
            "插件请求了未授权域名：" to "error.unauthorized_domain",
            "来源请求失败 (HTTP " to "error.source_http",
            "音频缓存失败（HTTP " to "error.audio_http"
        )
        for ((prefix, key) in patterns) {
            if (message.startsWith(prefix)) {
                val detail = message.removePrefix(prefix).removeSuffix(")").removeSuffix("）")
                return textForLanguage(language, key).format(detail)
            }
        }
        return message
    }

    internal fun textForLanguage(language: String, key: String): String {
        val value = entries[key] ?: return key
        return when (language) {
            TRADITIONAL -> value.traditional
            ENGLISH -> value.english
            else -> value.simplified
        }
    }

